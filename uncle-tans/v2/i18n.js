// saved choice → first supported browser language → Polish
let LANG = (() => {
  try { const s = JSON.parse(localStorage.getItem('v2_lang')); if (I18N[s]) return s; } catch {}
  return (navigator.languages || [navigator.language || '']).map(l => l.slice(0, 2)).find(l => I18N[l]) || 'pl';
})();

/** UI string with {placeholders} */
function t(key, vars = {}) {
  const s = I18N[LANG][key] ?? I18N.pl[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}
/** Name of a product / category / variant option in the current language */
const nameOf = x => (LANG === 'pl' ? x.name : x[LANG]) || x.name;
/** Secondary name: the English one in Polish (as on the printed menu), otherwise the Polish original */
const altNameOf = x => { const alt = LANG === 'pl' ? x.en : x.name; return alt && alt !== nameOf(x) ? alt : ''; };
/** { pl, en, de, vi } text */
const tx = o => (o ? o[LANG] ?? o.pl : '');

/** Static HTML: data-i18n (innerHTML), data-i18n-ph (placeholder), data-i18n-aria (aria-label) */
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
